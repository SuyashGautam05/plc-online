// Run from the project root:  node make-lesson-map.js
// Scans pages/<Folder>/<File>.html and writes lesson-map.js
// (short lesson name -> "Folder/File.html"). Re-run when you add a lesson.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, 'pages');
const map = {};
for (const folder of fs.readdirSync(root, { withFileTypes: true })) {
    if (!folder.isDirectory()) continue;
    for (const f of fs.readdirSync(path.join(root, folder.name))) {
        if (!/\.html$/i.test(f) || /^index\.html$/i.test(f)) continue;
        const name = f.replace(/\.html$/i, '');
        if (map[name]) console.warn('Duplicate lesson name (skipped):', name, '->', folder.name);
        else map[name] = folder.name + '/' + f;
    }
}
const keys = Object.keys(map).sort();
const out = '// AUTO-GENERATED by make-lesson-map.js - do not edit by hand.\nwindow.LESSON_MAP = ' +
    JSON.stringify(Object.fromEntries(keys.map(k => [k, map[k]])), null, 2) + ';\n';
fs.writeFileSync(path.join(__dirname, 'lesson-map.js'), out);
console.log('lesson-map.js written:', keys.length, 'lessons');